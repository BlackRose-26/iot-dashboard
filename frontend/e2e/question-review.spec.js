import { test, expect } from '@playwright/test'

test('review one practice question, correct it, and return to the saved decision', async ({
  page,
}) => {
  await page.goto('/admin/question-review')
  await expect(page).toHaveURL(/admin\/login$/)
  await page.getByLabel('Username', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STACK_TEST_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/admin\/question-review$/)
  await page.goto('/admin/settings')
  await page.getByRole('link', { name: 'Review questions', exact: true }).click()
  await expect(page.getByText('0 of 325 reviewed')).toBeVisible()
  await page.getByRole('button', { name: 'Yes, that fits' }).click()
  await expect(page.getByText('1 of 325 reviewed')).toBeVisible()
  await page.getByLabel('Show questions').selectOption('reviewed')
  await page.getByRole('button', { name: 'Change the meaning' }).click()
  const topic = page.getByLabel('Pick the topic')
  await topic.selectOption((await topic.inputValue()) === 'knowledge' ? 'social' : 'knowledge')
  await page.getByLabel('Which part?').selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Save my change' }).click()
  await expect(page.getByText(/^Your change:/)).toBeVisible()
  await page.reload()
  await page.getByLabel('Show questions').selectOption('reviewed')
  await expect(page.getByText(/^Your change:/)).toBeVisible()
  await page.getByRole('button', { name: 'Too unclear to use' }).click()
  await expect(page.getByText('Marked unclear', { exact: true })).toBeVisible()
  await page.getByLabel('Show questions').selectOption('all')
  await page.getByLabel('Find a question').fill('zzzzzzzzz')
  await expect(page.getByText('No questions match this view.')).toBeVisible()
  await page.getByRole('button', { name: 'Show all questions' }).click()
  await page.setViewportSize({ width: 360, height: 800 })
  await expect(page.getByRole('button', { name: 'Change the meaning' })).toBeVisible()
  expect(
    await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth),
  ).toBeTruthy()
})

test('review from Stack Intelligence and return to the same draft and reply', async ({ page }) => {
  await page.goto('/admin/login')
  await page.getByLabel('Username', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STACK_TEST_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/admin\/overview$/)
  await page.getByRole('button', { name: /Stack Intelligence/ }).click()
  const chat = page.getByRole('complementary', { name: 'Stack Intelligence assistant' })
  const question = chat.getByLabel('Ask Stack Intelligence')
  await question.fill('Show the average score.')
  await chat.getByRole('button', { name: 'Send question' }).click()
  const reviewReply = chat.getByRole('button', { name: 'Review this reply' })
  await expect(reviewReply).toBeVisible()
  await question.fill('My unsent draft')
  await chat.getByRole('button', { name: 'Review practice questions' }).click()
  const practice = chat.getByRole('region', { name: 'Practice question review' })
  await expect(practice.getByRole('progressbar')).toBeVisible()
  const count = await practice.getByRole('progressbar').getAttribute('value')
  await practice.getByRole('button', { name: 'Yes, that fits' }).click()
  await expect(practice.getByRole('progressbar')).toHaveAttribute(
    'value',
    String(Number(count) + 1),
  )
  await chat.getByRole('button', { name: 'Back to chat' }).click()
  await expect(question).toHaveValue('My unsent draft')
  await expect(
    chat.getByRole('log').getByText('Show the average score.', { exact: true }),
  ).toBeVisible()
  await reviewReply.click()
  const dialog = page.getByRole('dialog', { name: 'Review this reply' })
  await expect(dialog.getByLabel('What was the question about?')).toHaveValue('scores')
  await dialog.getByRole('button', { name: 'Save for approval' }).click()
  const approve = dialog.getByRole('button', { name: 'Approve example' })
  await expect(approve).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await approve.click()
  await expect(dialog.getByRole('status')).toContainText('Approved')
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  await expect(question).toHaveValue('My unsent draft')
  await expect(page).toHaveURL(/admin\/overview$/)
})
